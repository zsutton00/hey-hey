const fs = require("fs");
const path = require("path");
const yaml = require("js-yaml");

const openapiRoot = fs.realpathSync(
  require("child_process")
    .execFileSync(
      process.execPath,
      [path.join(__dirname, "openapi-root.cjs")],
      {
        encoding: "utf8",
      },
    )
    .trim(),
);
const sourcePath = path.join(
  openapiRoot,
  "specs/schemas/private-beta-access.yaml",
);
const outputPath = path.resolve(
  "src/clients/private-beta-access-contract.generated.ts",
);
const document = yaml.load(fs.readFileSync(sourcePath, "utf8"));
const properties = document.PrivateBetaAccessRequestSubmissionDto?.properties;

if (
  !properties ||
  typeof properties !== "object" ||
  Array.isArray(properties)
) {
  throw new Error(
    `PrivateBetaAccessRequestSubmissionDto properties are missing from ${sourcePath}`,
  );
}

const constraints = {
  name: pick(properties.name, ["minLength", "maxLength"]),
  workEmail: pick(properties.workEmail, ["minLength", "maxLength"]),
  organizationName: pick(properties.organizationName, [
    "minLength",
    "maxLength",
  ]),
  teamSize: pick(properties.teamSize, ["minimum", "maximum"]),
  productContext: pick(properties.productContext, ["minLength", "maxLength"]),
  accessRationale: pick(properties.accessRationale, ["minLength", "maxLength"]),
};

const output = [
  "// AUTO-GENERATED by scripts/generate-private-beta-access-contract.cjs.",
  "// Source of truth: openapi/specs/schemas/private-beta-access.yaml.",
  "",
  `export const privateBetaAccessRequestFieldConstraints = ${JSON.stringify(constraints, null, 2)} as const;`,
  "",
].join("\n");

fs.writeFileSync(outputPath, output);

function pick(source, keys) {
  if (!source || typeof source !== "object" || Array.isArray(source)) {
    throw new Error("Expected a private-beta field schema object");
  }
  return Object.fromEntries(keys.map((key) => [key, source[key]]));
}
