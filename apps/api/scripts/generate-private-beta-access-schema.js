const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const { resolveOpenapiRoot } = require('./openapi-root');
const { resolveGeneratedRoot } = require('./generated-root');

const openapiRoot = resolveOpenapiRoot();
const sourcePath = path.join(
  openapiRoot,
  'specs/schemas/private-beta-access.yaml',
);
const document = yaml.load(fs.readFileSync(sourcePath, 'utf8'));
const schemas = [
  {
    schemaName: 'PrivateBetaAccessRequestSubmissionDto',
    exportName: 'privateBetaAccessRequestSubmissionJsonSchema',
    outputPath: path.resolve(
      resolveGeneratedRoot(),
      'private-beta-access-request-submission.schema.ts',
    ),
  },
  {
    schemaName: 'PrivateBetaAccessRequestDecisionInputDto',
    exportName: 'privateBetaAccessRequestDecisionInputJsonSchema',
    outputPath: path.resolve(
      resolveGeneratedRoot(),
      'private-beta-access-request-decision.schema.ts',
    ),
  },
];

for (const definition of schemas) {
  const schema = document[definition.schemaName];
  if (!schema || typeof schema !== 'object' || Array.isArray(schema)) {
    throw new Error(`${definition.schemaName} is missing from ${sourcePath}`);
  }

  const output = [
    '// AUTO-GENERATED by scripts/generate-private-beta-access-schema.js.',
    '// Source of truth: openapi/specs/schemas/private-beta-access.yaml.',
    '',
    `export const ${definition.exportName} = ${JSON.stringify(schema, null, 2)} as const;`,
    '',
  ].join('\n');

  fs.mkdirSync(path.dirname(definition.outputPath), { recursive: true });
  fs.writeFileSync(definition.outputPath, output);
}
