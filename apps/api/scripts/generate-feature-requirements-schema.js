const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');
const yaml = require('js-yaml');
const { resolveGeneratedRoot } = require('./generated-root');

const rootResult = spawnSync(
  process.execPath,
  [path.join(__dirname, 'openapi-root.js')],
  {
    encoding: 'utf8',
  },
);
if (rootResult.status !== 0) {
  throw new Error(rootResult.stderr || 'Unable to resolve OpenAPI root.');
}

const schemasRoot = path.join(rootResult.stdout.trim(), 'specs', 'schemas');
const entryPath = path.join(schemasRoot, 'tasks.yaml');
const documents = new Map();
const load = (file) => {
  const resolved = path.resolve(file);
  const relative = path.relative(schemasRoot, resolved);
  if (relative.startsWith('..') || path.isAbsolute(relative)) {
    throw new Error(
      `Feature requirements schema references outside ${schemasRoot}.`,
    );
  }
  if (!documents.has(resolved)) {
    documents.set(resolved, yaml.load(fs.readFileSync(resolved, 'utf8')));
  }
  return documents.get(resolved);
};

const resolveRef = (ref, source) => {
  const [fileRef, fragment] = ref.split('#', 2);
  if (fragment === undefined || !fragment.startsWith('/')) {
    throw new Error(
      `Feature requirements schema requires a JSON pointer: ${ref}`,
    );
  }
  const target = fileRef ? path.resolve(path.dirname(source), fileRef) : source;
  const value = fragment
    .slice(1)
    .split('/')
    .map((part) => part.replaceAll('~1', '/').replaceAll('~0', '~'))
    .reduce((current, key) => current[key], load(target));
  return { target, key: `${target}#${fragment}`, value };
};

const dereference = (value, source = entryPath, stack = []) => {
  if (Array.isArray(value))
    return value.map((item) => dereference(item, source, stack));
  if (typeof value !== 'object' || value === null) return value;
  if (typeof value.$ref === 'string') {
    const resolved = resolveRef(value.$ref, source);
    if (stack.includes(resolved.key))
      throw new Error(`Circular schema ref ${resolved.key}`);
    const { $ref, ...siblings } = value;
    return dereference({ ...resolved.value, ...siblings }, resolved.target, [
      ...stack,
      resolved.key,
    ]);
  }
  return Object.fromEntries(
    Object.entries(value).map(([key, child]) => [
      key,
      dereference(child, source, stack),
    ]),
  );
};

const section = load(entryPath).FeatureRequirementsSection;
if (!section)
  throw new Error('FeatureRequirementsSection is missing from tasks.yaml.');
const output = path.join(
  resolveGeneratedRoot(),
  'feature-requirements.schema.ts',
);
fs.mkdirSync(path.dirname(output), { recursive: true });
fs.writeFileSync(
  output,
  `/* Generated by scripts/generate-feature-requirements-schema.js. Do not edit. */\n` +
    `export const featureRequirementsJsonSchema = ${JSON.stringify(dereference(section), null, 2)} as const;\n`,
);
