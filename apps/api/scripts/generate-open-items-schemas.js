const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const { resolveOpenapiRoot } = require('./openapi-root');
const { resolveGeneratedRoot } = require('./generated-root');

const root = resolveOpenapiRoot();
const source = path.join(root, 'specs/schemas/open-items.yaml');

function resolve(schema, file) {
  if (Array.isArray(schema)) return schema.map((item) => resolve(item, file));
  if (!schema || typeof schema !== 'object') return schema;
  if (schema.$ref) {
    const [relative, fragment] = schema.$ref.split('#/');
    const target = relative ? path.resolve(path.dirname(file), relative) : file;
    const document = yaml.load(fs.readFileSync(target, 'utf8'));
    return resolve(
      fragment.split('/').reduce((value, key) => value[key], document),
      target,
    );
  }
  const result = Object.fromEntries(
    Object.entries(schema)
      .filter(([key]) => key !== 'nullable')
      .map(([key, value]) => [key, resolve(value, file)]),
  );
  return schema.nullable ? { anyOf: [result, { type: 'null' }] } : result;
}

const document = yaml.load(fs.readFileSync(source, 'utf8'));
const schemaNames = [
  'OpenItemRef',
  'OpenItemGroupId',
  'ActivateOpenItemRequest',
  'SetOpenItemNoteRequest',
  'SetOpenItemPinRequest',
  'MoveOpenItemRequest',
  'RemoveOpenItemRequest',
  'RemoveOpenItemsRequest',
  'CreateOpenItemGroupRequest',
  'RenameOpenItemGroupRequest',
  'DeleteOpenItemGroupRequest',
  'SetOpenItemGroupDisclosureRequest',
  'MoveOpenItemGroupRequest',
  'AssignOpenItemsToGroupRequest',
  'UngroupOpenItemsRequest',
  'MoveOpenItemGroupMemberRequest',
  'MigrateOpenItemsRequest',
  'ResetOpenItemsRequest',
  'SetOpenItemGoalFilterRequest',
  'SetOpenItemGoalDisclosureRequest',
  'PromoteGroupToGoalRequest',
];

const schemas = Object.fromEntries(
  schemaNames.map((name) => {
    if (!document[name]) {
      throw new Error(`${name} is missing from ${source}`);
    }
    return [name, resolve(document[name], source)];
  }),
);

fs.writeFileSync(
  path.join(resolveGeneratedRoot(), 'open-items.schemas.ts'),
  [
    '// AUTO-GENERATED by scripts/generate-open-items-schemas.js.',
    '// Source of truth: openapi/specs/schemas/open-items.yaml.',
    '',
    `export const openItemsJsonSchemas = ${JSON.stringify(schemas, null, 2)} as const;`,
    '',
  ].join('\n'),
);
