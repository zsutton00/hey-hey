#!/usr/bin/env node

/**
 * Generates a barrel export file (models.ts) for all model files
 * This is needed because typescript-nestjs generator doesn't create it by default
 */

const fs = require('fs');
const path = require('path');
const { resolveGeneratedRoot } = require('./generated-root');

const GENERATED_DIR = resolveGeneratedRoot();
const MODEL_DIR = path.join(GENERATED_DIR, 'model');
const OUTPUT_FILE = path.join(MODEL_DIR, 'models.ts');

console.log('📦 Generating model barrel exports...');

try {
  // Check if model directory exists
  if (!fs.existsSync(MODEL_DIR)) {
    console.error('❌ Model directory does not exist:', MODEL_DIR);
    process.exit(1);
  }

  // Read all .ts files in the model directory (excluding models.ts itself)
  const files = fs.readdirSync(MODEL_DIR)
    .filter(file => file.endsWith('.ts') && file !== 'models.ts')
    .sort();

  if (files.length === 0) {
    console.warn('⚠️  No model files found in', MODEL_DIR);
    process.exit(0);
  }

  // Generate export statements
  const exports = files.map(file => {
    const basename = path.basename(file, '.ts');
    return `export * from './${basename}';`;
  }).join('\n');

  // Write the barrel file
  const content = `/* tslint:disable */
/* eslint-disable */
/**
 * Auto-generated barrel export file for models
 * DO NOT EDIT - This file is automatically generated
 */

${exports}
`;

  fs.writeFileSync(OUTPUT_FILE, content, 'utf-8');

  console.log(`✅ Generated ${OUTPUT_FILE}`);
  console.log(`📊 Exported ${files.length} model files`);

  // Create stub files for variables.ts and configuration.ts if they don't exist
  // These are referenced by index.ts but not generated when using globalProperty: "models"
  const stubFiles = [
    {
      path: path.join(GENERATED_DIR, 'variables.ts'),
      content: `/* tslint:disable */
/* eslint-disable */
/**
 * Auto-generated stub file for variables
 * This file is created because the generator is configured to only generate models
 */

export const BASE_PATH = '/api/v1';
`
    },
    {
      path: path.join(GENERATED_DIR, 'configuration.ts'),
      content: `/* tslint:disable */
/* eslint-disable */
/**
 * Auto-generated stub file for configuration
 * This file is created because the generator is configured to only generate models
 */

export class Configuration {
  constructor() {}
}
`
    }
  ];

  stubFiles.forEach(stub => {
    if (!fs.existsSync(stub.path)) {
      fs.writeFileSync(stub.path, stub.content, 'utf-8');
      console.log(`✅ Generated stub file: ${path.basename(stub.path)}`);
    } else {
      console.log(`ℹ️  Stub file already exists: ${path.basename(stub.path)}`);
    }
  });

} catch (error) {
  console.error('❌ Error generating model barrel exports:', error);
  process.exit(1);
}
