const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const { resolveOpenapiRoot } = require('./openapi-root');
const { resolveGeneratedRoot } = require('./generated-root');

const source = path.join(
  resolveOpenapiRoot(),
  'specs/schemas/demo-sandboxes.yaml',
);
const document = yaml.load(fs.readFileSync(source, 'utf8'));
const schemaExports = [
  ['setDemoTemplateJsonSchema', 'SetDemoTemplateDto'],
  ['provisionDemoSandboxJsonSchema', 'ProvisionDemoSandboxDto'],
  ['demoSandboxProgramJsonSchema', 'DemoSandboxProgramDto'],
];

// Local references ("#/Name") become self-contained "#/definitions/Name".
function standalone(name) {
  const localRefs = new Set(
    [...JSON.stringify(document[name]).matchAll(/"\$ref":"#\/([^"]+)"/g)].map(
      (match) => match[1],
    ),
  );
  const schema = {
    ...document[name],
    ...(localRefs.size > 0
      ? {
          definitions: Object.fromEntries(
            [...localRefs].map((ref) => [ref, document[ref]]),
          ),
        }
      : {}),
  };
  return JSON.parse(
    JSON.stringify(schema).replaceAll('"#/', '"#/definitions/'),
  );
}

fs.writeFileSync(
  path.join(resolveGeneratedRoot(), 'demo-sandbox.schema.ts'),
  '// Generated by scripts/generate-demo-sandbox-schema.js. Do not edit.\n' +
    schemaExports
      .map(
        ([exportName, schemaName]) =>
          `export const ${exportName} = ${JSON.stringify(standalone(schemaName), null, 2)} as const;\n`,
      )
      .join('\n'),
);
