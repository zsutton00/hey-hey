const fs = require('fs');
const path = require('path');
const yaml = require('js-yaml');
const { resolveOpenapiRoot } = require('./openapi-root');
const { resolveGeneratedRoot } = require('./generated-root');

const root = resolveOpenapiRoot();
const source = path.join(root, 'specs/schemas/work-item-execution-state.yaml');

function resolve(schema, file) {
  if (Array.isArray(schema)) return schema.map((item) => resolve(item, file));
  if (!schema || typeof schema !== 'object') return schema;
  if (schema.$ref) {
    const [relative, fragment] = schema.$ref.split('#/');
    const target = relative ? path.resolve(path.dirname(file), relative) : file;
    const document = yaml.load(fs.readFileSync(target, 'utf8'));
    return resolve(
      fragment.split('/').reduce((value, key) => value[key], document),
      target,
    );
  }
  // The OpenAPI discriminator only names the tag; the closed variants already
  // constrain it, and Ajv rejects its mapping keyword.
  const result = Object.fromEntries(
    Object.entries(schema)
      .filter(([key]) => key !== 'nullable' && key !== 'discriminator')
      .map(([key, value]) => [key, resolve(value, file)]),
  );
  if (!schema.nullable) return result;
  // A nullable enum lists null among its values; the type must admit it too.
  return { anyOf: [result, { type: 'null' }] };
}

const document = yaml.load(fs.readFileSync(source, 'utf8'));
const schemaNames = [
  'WorkItemExecutionStateObservation',
  'WorkItemExecutionStatePayload',
  'WorkItemExecutionStateBatchRequestDto',
];

const schemas = Object.fromEntries(
  schemaNames.map((name) => {
    if (!document[name]) {
      throw new Error(`${name} is missing from ${source}`);
    }
    return [name, resolve(document[name], source)];
  }),
);

fs.writeFileSync(
  path.join(resolveGeneratedRoot(), 'work-item-execution-state.schemas.ts'),
  [
    '// AUTO-GENERATED by scripts/generate-work-item-execution-state-schema.js.',
    '// Source of truth: openapi/specs/schemas/work-item-execution-state.yaml.',
    '',
    `export const workItemExecutionStateJsonSchemas = ${JSON.stringify(schemas, null, 2)} as const;`,
    '',
  ].join('\n'),
);
