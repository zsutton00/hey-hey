#!/usr/bin/env node
/*
 * Finds OpenAPI operations and schemas that no consumer references.
 *
 * Usage:
 *   node scripts/find-unused-spec-content.js [--json out.json] [--markdown out.md]
 *        [--consumer name=/path/to/repo ...] [--only-spec api]
 *
 * Procedure (no model involved):
 *   1. Load every spec root and build a reference graph. Units are operations
 *      (method + path) and top-level definitions (schema files, components).
 *   2. Scan each consumer's hand-written source (generated output excluded) for
 *      identifier tokens and path literals.
 *   3. Detect API server handlers from NestJS controller decorators.
 *   4. Classify operations, then compute which definitions are reachable from
 *      something that is kept. Everything else is unused.
 *
 * Evidence is over-inclusive on purpose: any identifier that equals an
 * operationId or schema name counts as a reference, so a false "used" is
 * possible and a false "unused" should only come from dynamic access. Removal
 * is always confirmed by regenerating and building the consumers.
 */
