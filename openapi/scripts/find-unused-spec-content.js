// Spec model

const docCache = new Map();
const danglingFiles = new Set(); // referenced files that do not exist
function loadDoc(absFile) {
  if (!docCache.has(absFile)) {
    if (!fs.existsSync(absFile)) {
      danglingFiles.add(rel(absFile));
      docCache.set(absFile, null);
    } else docCache.set(absFile, yaml.load(fs.readFileSync(absFile, 'utf8')));
  }
  return docCache.get(absFile);
}

function unescapePointerSegment(segment) {
  return decodeURIComponent(segment).replace(/~1/g, '/').replace(/~0/g, '~');
}

function splitRef(fromFile, ref) {
  const hashIndex = ref.indexOf('#');
  const filePart = hashIndex === -1 ? ref : ref.slice(0, hashIndex);
  const pointer = hashIndex === -1 ? '' : ref.slice(hashIndex + 1);
  const file = filePart ? path.resolve(path.dirname(fromFile), filePart) : fromFile;
  const segments = pointer.split('/').slice(1).map(unescapePointerSegment);
  return { file, segments };
}

const rel = (absFile) => path.relative(REPO, absFile);

const SCHEMA_KEYWORDS = new Set(['type', 'properties', 'allOf', 'oneOf', 'anyOf', 'enum', '$ref', 'items', 'required']);

// 'components': OpenAPI document; 'single': the file is one schema; 'keys': each top-level key
// is a definition (schema files, path-item files); 'mixed': 'keys' plus a nested `components` block.
function fileMode(absFile) {
  const doc = loadDoc(absFile);
  if (!doc || typeof doc !== 'object') return 'keys';
  if (doc.openapi) return 'components';
  if (Object.keys(doc).some((key) => SCHEMA_KEYWORDS.has(key))) return 'single';
  if (doc.components) return 'mixed'; // top-level definitions plus a nested `components` block
  return 'keys';
}

// Unit id for the top-level definition a reference lands in.
function unitIdForRef(fromFile, ref) {
  const { file, segments } = splitRef(fromFile, ref);
  const mode = fileMode(file);
  if (mode === 'single') return `${rel(file)}#`;
  if (segments[0] === 'components' && segments.length >= 3) {
    return `${rel(file)}#/components/${segments[1]}/${segments[2]}`;
  }
  if (segments.length >= 1) return `${rel(file)}#/${segments[0]}`;
  return `${rel(file)}#`;
}

function collectRefs(node, fromFile, out) {
  if (Array.isArray(node)) {
    for (const item of node) collectRefs(item, fromFile, out);
    return;
  }
  if (!node || typeof node !== 'object') return;
  for (const [key, value] of Object.entries(node)) {
    if (key === '$ref' && typeof value === 'string') out.add(value);
    else if (key === 'mapping' && value && typeof value === 'object') {
      for (const target of Object.values(value)) if (typeof target === 'string') out.add(target);
    } else collectRefs(value, fromFile, out);
  }
}

function resolvePointer(fromFile, ref) {
  const { file, segments } = splitRef(fromFile, ref);
  let node = loadDoc(file);
  for (const segment of segments) {
    if (node == null) return { file, node: undefined };
    node = node[segment];
  }
  return { file, node };
}

function buildSpecModel(onlySpec) {
  const units = new Map(); // id -> { id, kind, file, name, refs:Set<unitId> }
  const operations = []; // { id, spec, method, path, operationId, tag, unitRefs:Set }

  function ensureUnit(id, kind, file, name) {
    if (!units.has(id)) units.set(id, { id, kind, file, name, refs: new Set() });
    return units.get(id);
  }

  // Register every top-level definition of a file as a unit (lazy for schema files).
  function registerFileUnits(absFile) {
    const doc = loadDoc(absFile);
    if (!doc || typeof doc !== 'object') return;
    const mode = fileMode(absFile);
    if (mode === 'single') {
      ensureUnit(`${rel(absFile)}#`, 'schema', absFile, path.basename(absFile, '.yaml'));
    } else {
      if (mode === 'components' || mode === 'mixed') {
        for (const [kind, entries] of Object.entries(doc.components || {})) {
          for (const name of Object.keys(entries || {})) {
            ensureUnit(`${rel(absFile)}#/components/${kind}/${name}`, kind, absFile, name);
          }
        }
      }
      if (mode === 'components') return;
      for (const name of Object.keys(doc).filter((key) => key !== 'components')) {
        ensureUnit(`${rel(absFile)}#/${name}`, absFile.includes(`${path.sep}paths${path.sep}`) ? 'pathItem' : 'schema', absFile, name);
      }
    }
  }

  const visitedFiles = new Set();
  function visitFile(absFile) {
    if (visitedFiles.has(absFile)) return;
    visitedFiles.add(absFile);
    registerFileUnits(absFile);
    const doc = loadDoc(absFile);
    if (!doc || typeof doc !== 'object') return;

    const refsOf = (node) => {
      const refs = new Set();
      collectRefs(node, absFile, refs);
      return refs;
    };
    const linkUnit = (unit, node) => {
      for (const ref of refsOf(node)) {
        const targetId = unitIdForRef(absFile, ref);
        unit.refs.add(targetId);
        visitFile(splitRef(absFile, ref).file);
      }
    };

    const mode = fileMode(absFile);
    if (mode === 'single') {
      linkUnit(units.get(`${rel(absFile)}#`), doc);
    } else {
      if (mode === 'components' || mode === 'mixed') {
        for (const [kind, entries] of Object.entries(doc.components || {})) {
          for (const [name, definition] of Object.entries(entries || {})) {
            linkUnit(units.get(`${rel(absFile)}#/components/${kind}/${name}`), definition);
          }
        }
      }
      if (mode === 'components') return;
      for (const [name, definition] of Object.entries(doc).filter(([key]) => key !== 'components')) {
        linkUnit(units.get(`${rel(absFile)}#/${name}`), definition);
      }
    }
  }

  for (const [spec, relFile] of Object.entries(SPEC_ROOTS)) {
    if (onlySpec && spec !== onlySpec) continue;
    const absFile = path.join(REPO, relFile);
    visitFile(absFile);
    const doc = loadDoc(absFile);
    for (const [route, rawItem] of Object.entries(doc.paths || {})) {
      let pathItem = rawItem;
      let itemFile = absFile;
      const itemRefs = new Set();
      if (rawItem && rawItem.$ref) {
        const resolved = resolvePointer(absFile, rawItem.$ref);
        pathItem = resolved.node;
        itemFile = resolved.file;
        visitFile(itemFile);
        itemRefs.add(unitIdForRef(absFile, rawItem.$ref));
      }
      if (!pathItem) continue;
      const sharedRefs = new Set();
      collectRefs(pathItem.parameters, itemFile, sharedRefs);
      // `x-*` entries shaped like operations are ignored by every generator, so nothing can call them.
      const extensionKeys = Object.keys(pathItem).filter(
        (key) => key.startsWith('x-') && pathItem[key] && typeof pathItem[key] === 'object' && (pathItem[key].operationId || pathItem[key].responses),
      );
      for (const method of [...HTTP_METHODS, ...extensionKeys]) {
        const operation = pathItem[method];
        if (!operation) continue;
        const refs = new Set();
        collectRefs(operation, itemFile, refs);
        for (const r of sharedRefs) refs.add(r);
        const unitRefs = new Set(itemRefs);
        for (const r of refs) {
          unitRefs.add(unitIdForRef(itemFile, r));
          visitFile(splitRef(itemFile, r).file);
        }
        operations.push({
          id: `${spec}:${method.toUpperCase()} ${route}`,
          spec,
          method: method.toUpperCase(),
          methodKey: method,
          extension: method.startsWith('x-'),
          path: route,
          operationId: operation.operationId || null,
          tag: (operation.tags && operation.tags[0]) || null,
          file: rel(itemFile),
          unitRefs,
        });
      }
    }
  }

  // Alternative entry-point files: load so their units exist, but they are not roots.
  for (const relFile of ORPHAN_CANDIDATE_FILES) {
    const absFile = path.join(REPO, relFile);
    if (fs.existsSync(absFile)) visitFile(absFile);
  }
  for (const entry of fs.readdirSync(path.join(REPO, 'specs/schemas'))) {
    if (entry.endsWith('.yaml')) visitFile(path.join(REPO, 'specs/schemas', entry));
  }

  return { units, operations };
}

