function summarize(results, scans, routeSets, model) {
  const count = (items, key) => items.reduce((acc, item) => ((acc[item[key]] = (acc[item[key]] || 0) + 1), acc), {});
  return {
    generatedAt: new Date().toISOString(),
    consumersChecked: scans.map((scan) => ({
      name: scan.consumer.name,
      root: scan.root,
      pinned: scan.consumer.pinned,
      filesScanned: scan.fileCount,
      routesResolved: routeSets.get(scan.consumer.name)?.routes.size,
      unresolvedRouteDecorators: routeSets.get(scan.consumer.name)?.unresolved,
    })),
    consumersNotChecked: [...CONSUMERS, ...OPT_IN_CONSUMERS].filter((c) => !scans.some((s) => s.consumer.name === c.name)).map((c) => c.name),
    operationCounts: count(model.operations, 'status'),
    definitionCounts: count(results.definitions, 'status'),
  };
}

function lineOf(file, matcher) {
  const lines = fs.readFileSync(path.join(REPO, file), 'utf8').split('\n');
  const index = lines.findIndex((line) => matcher.test(line));
  return index === -1 ? null : index + 1;
}

function locate(item) {
  try {
    if (item.method) {
      const file = item.file;
      const escapedPath = item.path.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      const start = lineOf(file, new RegExp(`^\\s*['"]?${escapedPath}['"]?:`));
      return start && `${file}:${start}`;
    }
    const hashPath = item.id.split('#')[1];
    const segments = hashPath.split('/').filter(Boolean);
    const key = segments[segments.length - 1];
    const line = lineOf(item.file, new RegExp(`^\\s*['"]?${key.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}['"]?:`));
    return line && `${item.file}:${line}`;
  } catch {
    return null;
  }
}

function renderMarkdown(summary, model, results, orphanFiles) {
  const out = [];
  out.push('# Unused OpenAPI content report', '', `Generated ${summary.generatedAt}.`, '');
  out.push('## Consumers checked', '');
  for (const c of summary.consumersChecked) {
    out.push(`- ${c.name}${c.pinned ? ' (pinned spec version)' : ''}: ${c.filesScanned} hand-written files scanned${c.routesResolved != null ? `, ${c.routesResolved} server routes resolved` : ''}`);
  }
  if (summary.consumersNotChecked.length) out.push(`- NOT checked: ${summary.consumersNotChecked.join(', ')}`);
  out.push('', '## Counts', '', `Operations: ${JSON.stringify(summary.operationCounts)}`, '', `Definitions: ${JSON.stringify(summary.definitionCounts)}`, '');
  const apiScan = summary.consumersChecked.find((c) => c.name === 'api');
  if (apiScan && apiScan.unresolvedRouteDecorators?.length) {
    out.push(`API route decorators that could not be resolved statically (${apiScan.unresolvedRouteDecorators.length}); operations on these routes may be mislabelled as unreferenced:`, '');
    for (const line of apiScan.unresolvedRouteDecorators.slice(0, 40)) out.push(`- ${line}`);
    out.push('');
  }

  const section = (title, items, render) => {
    out.push(`## ${title} (${items.length})`, '');
    for (const item of items) out.push(render(item));
    out.push('');
  };
  const opLine = (op) => `- \`${op.spec}\` ${op.method} ${op.path} (${op.operationId}) [${op.tag}] — ${locate(op) || op.file}`;
  section('Operations with no handler and no caller', model.operations.filter((op) => op.status === 'unreferenced'), opLine);
  section('Operations with a server handler but no caller', model.operations.filter((op) => op.status === 'handler-only'), (op) => `${opLine(op)}\n  handler: ${op.handlerFiles.join(', ')}`);
  section('Operations kept because they are the only path to a model a consumer imports', model.operations.filter((op) => op.status === 'needed-for-models'), (op) => `${opLine(op)}\n  models: ${op.neededModels.join(', ')}`);
  section('Operations referenced only by tests', model.operations.filter((op) => op.status === 'used-by-tests-only'), opLine);
  section('Operations held by a pinned consumer', model.operations.filter((op) => op.status === 'held-by-pinned-consumer'), (op) => `${opLine(op)}\n  pinned: ${op.pinnedCallers.map((e) => e.consumer).join(', ')}`);
  section('Operations with unknown status', model.operations.filter((op) => op.status === 'unknown'), opLine);
  section('Unused definitions', results.definitions.filter((d) => d.status === 'unused'), (d) => `- ${d.id} (${d.kind}) — ${locate(d) || d.file}`);
  section('Definitions kept alive only by handler-only operations', results.definitions.filter((d) => d.status === 'only-via-handler-only-operations'), (d) => `- ${d.id} (${d.kind})`);
  section('Definitions held by pinned consumers', results.definitions.filter((d) => d.status === 'held-by-pinned-consumer'), (d) => `- ${d.id} (${d.kind}): ${d.evidence.filter((e) => ['graphs', 'embeddings'].includes(e.consumer)).map((e) => e.consumer).join(', ')}`);
  section('Spec files nothing reads', orphanFiles, (file) => `- ${file}`);
  return `${out.join('\n')}\n`;
}

function findOrphanFiles() {
  const read = new Set();
  for (const relFile of Object.values(SPEC_ROOTS)) read.add(path.join(REPO, relFile));
  const orphans = [];
  for (const relFile of ORPHAN_CANDIDATE_FILES) {
    if (fs.existsSync(path.join(REPO, relFile))) orphans.push(relFile);
  }
  const pathsDir = path.join(REPO, 'specs/paths');
  if (fs.existsSync(pathsDir)) {
    for (const entry of fs.readdirSync(pathsDir)) orphans.push(`specs/paths/${entry}`);
  }
  return orphans;
}

