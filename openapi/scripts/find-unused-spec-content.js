function parseArgs(argv) {
  const args = { consumers: {}, json: null, markdown: null, onlySpec: null };
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--json') args.json = argv[(i += 1)];
    else if (argv[i] === '--markdown') args.markdown = argv[(i += 1)];
    else if (argv[i] === '--only-spec') args.onlySpec = argv[(i += 1)];
    else if (argv[i] === '--consumer') {
      const [name, dir] = argv[(i += 1)].split('=');
      args.consumers[name] = path.resolve(dir);
    } else throw new Error(`Unknown argument ${argv[i]}`);
  }
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const started = Date.now();
  const model = buildSpecModel(args.onlySpec);

  const scans = [];
  for (const consumer of CONSUMERS) {
    const root = args.consumers[consumer.name] || path.resolve(CONSUMER_BASE, consumer.dir);
    if (!fs.existsSync(root)) throw new Error(`Consumer ${consumer.name} not found at ${root}`);
    scans.push(scanConsumer(consumer, root));
  }
  for (const consumer of OPT_IN_CONSUMERS) {
    if (args.consumers[consumer.name]) scans.push(scanConsumer(consumer, args.consumers[consumer.name]));
  }
  // The spec repo's own scripts read the specs by name (contract validators, generators).
  scans.push(scanConsumer({ name: 'openapi-scripts', role: 'client', pinned: false }, path.join(CONSUMER_BASE, 'scripts')));

  const routeSets = new Map();
  const apiScan = scans.find((scan) => scan.consumer.name === 'api');
  if (apiScan) routeSets.set('api', extractRoutes(apiScan));

  const results = classify(model, scans, routeSets);
  const summary = summarize(results, scans, routeSets, model);
  const orphanFiles = findOrphanFiles();

  if (args.json) {
    fs.writeFileSync(
      args.json,
      JSON.stringify(
        {
          summary,
          orphanFiles,
          operations: model.operations.map((op) => ({
            id: op.id, spec: op.spec, method: op.method, methodKey: op.methodKey, extension: op.extension, path: op.path, operationId: op.operationId, tag: op.tag, file: op.file,
            status: op.status, handlerFiles: op.handlerFiles, callers: op.callers, pinnedCallers: op.pinnedCallers,
            refs: [...op.unitRefs],
          })),
          definitions: results.definitions,
        },
        null,
        2,
      ),
    );
  }
  const markdown = renderMarkdown(summary, model, results, orphanFiles);
  if (args.markdown) fs.writeFileSync(args.markdown, markdown);
  else process.stdout.write(markdown);
  process.stderr.write(`analysis finished in ${((Date.now() - started) / 1000).toFixed(1)}s\n`);
}

main();
