function buildConstantMap(sources) {
  const constants = new Map();
  const declaration = /(?:export\s+)?const\s+([A-Za-z_][A-Za-z0-9_]*)\s*(?::\s*[^=]+)?=\s*((?:'[^'\n]*'|"[^"\n]*"|`[^`\n]*`)(?:\s*\+\s*(?:'[^'\n]*'|"[^"\n]*"|`[^`\n]*`|[A-Za-z_][A-Za-z0-9_]*))*)\s*(?:as const)?\s*;/g;
  for (const source of sources) {
    for (const match of source.matchAll(declaration)) {
      if (!constants.has(match[1])) constants.set(match[1], match[2]);
    }
  }
  return constants;
}

function evalPathExpression(expression, constants, depth = 0) {
  if (depth > 8 || expression == null) return null;
  const expr = expression.trim();
  if (!expr) return '';
  const parts = [];
  let current = '';
  let quote = null;
  for (let i = 0; i < expr.length; i += 1) {
    const ch = expr[i];
    if (quote) {
      current += ch;
      if (ch === quote && expr[i - 1] !== '\\') quote = null;
    } else if (ch === "'" || ch === '"' || ch === '`') {
      quote = ch;
      current += ch;
    } else if (ch === '+') {
      parts.push(current);
      current = '';
    } else current += ch;
  }
  parts.push(current);
  let result = '';
  for (const rawPart of parts) {
    const part = rawPart.trim();
    if (!part) continue;
    const literal = part.match(/^(['"`])([\s\S]*)\1$/);
    if (literal) {
      let value = literal[2];
      let unresolved = false;
      value = value.replace(/\$\{([^}]*)\}/g, (_, inner) => {
        const resolved = evalPathExpression(inner, constants, depth + 1);
        if (resolved == null) unresolved = true;
        return resolved == null ? '' : resolved;
      });
      if (unresolved) return null;
      result += value;
    } else if (/^[A-Za-z_][A-Za-z0-9_.]*$/.test(part)) {
      const name = part.split('.').pop();
      if (!constants.has(name)) return null;
      const resolved = evalPathExpression(constants.get(name), constants, depth + 1);
      if (resolved == null) return null;
      result += resolved;
    } else return null;
  }
  return result;
}

function splitDecoratorArgument(source, openIndex) {
  // Returns the raw argument text of the decorator call starting at `(`.
  let depth = 0;
  let quote = null;
  for (let i = openIndex; i < source.length; i += 1) {
    const ch = source[i];
    if (quote) {
      if (ch === quote && source[i - 1] !== '\\') quote = null;
    } else if (ch === "'" || ch === '"' || ch === '`') quote = ch;
    else if (ch === '(') depth += 1;
    else if (ch === ')') {
      depth -= 1;
      if (depth === 0) return source.slice(openIndex + 1, i);
    }
  }
  return null;
}

function firstPathArgument(raw) {
  if (raw == null) return null;
  const trimmed = raw.replace(/^\s*\/\/[^\n]*$/gm, '').replace(/\/\*[\s\S]*?\*\//g, '').trim();
  if (!trimmed) return '';
  const object = trimmed.match(/^\{[\s\S]*?path\s*:\s*([^,}]+)/);
  if (object) return object[1].trim();
  if (trimmed.startsWith('[')) return trimmed.slice(1).split(',')[0].trim();
  // first top-level argument
  let depth = 0;
  let quote = null;
  for (let i = 0; i < trimmed.length; i += 1) {
    const ch = trimmed[i];
    if (quote) {
      if (ch === quote && trimmed[i - 1] !== '\\') quote = null;
    } else if (ch === "'" || ch === '"' || ch === '`') quote = ch;
    else if ('([{'.includes(ch)) depth += 1;
    else if (')]}'.includes(ch)) depth -= 1;
    else if (ch === ',' && depth === 0) return trimmed.slice(0, i).trim();
  }
  return trimmed;
}

function extractRoutes(scan) {
  const constants = buildConstantMap(scan.constSources);
  const routes = new Map(); // "METHOD path" -> files
  const unresolved = [];
  const METHOD_DECORATORS = { Get: 'GET', Post: 'POST', Put: 'PUT', Patch: 'PATCH', Delete: 'DELETE', Options: 'OPTIONS', Head: 'HEAD', Sse: 'GET' };

  for (const { relFile, text } of scan.controllerFiles) {
    const decorators = [];
    for (const match of text.matchAll(/@(Controller|Get|Post|Put|Patch|Delete|Options|Head|Sse|All)\s*\(/g)) {
      const open = match.index + match[0].length - 1;
      decorators.push({ name: match[1], index: match.index, raw: splitDecoratorArgument(text, open) });
    }
    // Pair each Controller decorator with the method decorators that follow until the next Controller.
    let prefixes = [''];
    for (const decorator of decorators) {
      if (decorator.name === 'Controller') {
        const argument = firstPathArgument(decorator.raw);
        const evaluated = argument === '' ? '' : evalPathExpression(argument, constants);
        if (evaluated == null) {
          unresolved.push(`${relFile}: @Controller(${(decorator.raw || '').trim().slice(0, 80)})`);
          prefixes = null;
        } else prefixes = [evaluated];
        continue;
      }
      if (prefixes == null) continue;
      const argument = firstPathArgument(decorator.raw);
      const evaluated = argument === '' ? '' : evalPathExpression(argument, constants);
      if (evaluated == null) {
        unresolved.push(`${relFile}: @${decorator.name}(${(decorator.raw || '').trim().slice(0, 80)})`);
        continue;
      }
      const methods = decorator.name === 'All' ? ['GET', 'POST', 'PUT', 'PATCH', 'DELETE'] : [METHOD_DECORATORS[decorator.name]];
      for (const prefix of prefixes) {
        const full = normalizePath(`${prefix}/${evaluated}`.replace(/\/+/g, '/'));
        for (const method of methods) {
          const key = `${method} ${full}`;
          if (!routes.has(key)) routes.set(key, []);
          if (!routes.get(key).includes(relFile)) routes.get(key).push(relFile);
        }
      }
    }
  }
  return { routes, unresolved };
}

// ---------------------------------------------------------------------------
// Classification

function snakeCase(name) {
  return name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/([A-Z]+)([A-Z][a-z])/g, '$1_$2').toLowerCase();
}

// Names a generator may emit for a spec name in the consumer's language.
function nameVariants(name) {
  return [...new Set([name, snakeCase(name)])];
}

// A client often builds a request from a base URL plus a trailing path, so a literal that is a
// trailing part of the spec path (with at least one literal segment) counts as a reference.
function pathSuffixMatches(literal, normalizedPath) {
  if (literal === normalizedPath) return true;
  return normalizedPath.endsWith(`/${literal}`) && literal.split('/').some((segment) => segment && segment !== '{}');
}

function summarizeEvidence(scans, names, { paths: pathKeys = [], suffixPaths = false } = {}) {
  // Returns evidence grouped by consumer.
  const evidence = [];
  for (const scan of scans) {
    const hits = { prod: [], test: [], handler: [] };
    for (const name of names) {
      for (const variant of nameVariants(name)) {
        const entry = scan.tokens.get(variant);
        if (!entry) continue;
        for (const bucket of Object.keys(hits)) hits[bucket].push(...entry[bucket].map((file) => `${variant} @ ${file}`));
      }
    }
    for (const key of pathKeys) {
      const matched = suffixPaths ? [...scan.paths].filter(([literal]) => pathSuffixMatches(literal, key)) : [[key, scan.paths.get(key)]];
      for (const [literal, entry] of matched) {
        if (!entry) continue;
        for (const bucket of Object.keys(hits)) hits[bucket].push(...entry[bucket].map((file) => `path ${literal} @ ${file}`));
      }
    }
    if (hits.prod.length || hits.test.length || hits.handler.length) {
      evidence.push({
        consumer: scan.consumer.name,
        pinned: scan.consumer.pinned,
        prod: hits.prod.slice(0, 3),
        test: hits.test.slice(0, 3),
        handler: hits.handler.slice(0, 3),
        hasProd: hits.prod.length > 0,
        hasTest: hits.test.length > 0,
        hasHandler: hits.handler.length > 0,
      });
    }
  }
  return evidence;
}

function classify(model, scans, routeSets) {
  const { units, operations } = model;
  const apiScan = scans.find((scan) => scan.consumer.name === 'api');
  const apiRoutes = routeSets.get('api');

  // --- operations
  const serverScans = new Map(scans.map((scan) => [scan.consumer.name, scan]));
  const suffixMatches = (scan, normalizedPath) => {
    const hits = [];
    for (const [literal, entry] of scan.paths) {
      if (pathSuffixMatches(literal, normalizedPath)) hits.push(...[...entry.prod, ...entry.test, ...entry.handler]);
    }
    return [...new Set(hits)].slice(0, 3);
  };

  for (const op of operations) {
    const normalizedPath = normalizePath(op.path);
    const names = op.operationId ? [op.operationId] : [];
    const serverName = SERVER_OF_SPEC[op.spec];
    // Callers: every consumer except the one implementing the spec.
    op.evidence = summarizeEvidence(scans.filter((scan) => scan.consumer.name !== serverName), names, { paths: [normalizedPath], suffixPaths: op.spec !== 'api' });
    if (op.spec === 'api') {
      op.handlerFiles = apiRoutes ? apiRoutes.routes.get(`${op.method} ${normalizedPath}`) || [] : [];
    } else if (serverName && serverScans.has(serverName)) {
      const serverScan = serverScans.get(serverName);
      const tokenHit = op.operationId && serverScan.tokens.has(op.operationId) ? [`${op.operationId}`] : [];
      op.handlerFiles = [...tokenHit, ...suffixMatches(serverScan, normalizedPath)];
    } else op.handlerFiles = [];
    const callers = op.evidence.filter((e) => e.hasProd || e.hasTest);
    op.callers = callers.filter((e) => !e.pinned);
    op.pinnedCallers = callers.filter((e) => e.pinned);
  }

  const hasHandlerInfo = Boolean(apiRoutes);
  for (const op of operations) {
    const onlyTests = op.callers.length > 0 && op.callers.every((e) => !e.hasProd);
    if (op.extension) op.status = 'unreferenced';
    else if (op.callers.length) op.status = onlyTests ? 'used-by-tests-only' : 'used';
    else if (op.pinnedCallers.length) op.status = 'held-by-pinned-consumer';
    else if (op.handlerFiles.length) op.status = 'handler-only';
    else if (op.spec === 'api' && !hasHandlerInfo) op.status = 'unknown';
    else op.status = 'unreferenced';
  }

  // --- definitions: reachability
  const nameToUnits = new Map();
  for (const unit of units.values()) {
    if (unit.kind === 'pathItem') continue;
    if (!nameToUnits.has(unit.name)) nameToUnits.set(unit.name, []);
    nameToUnits.get(unit.name).push(unit);
  }

  function reach(rootIds) {
    const seen = new Set();
    const stack = [...rootIds];
    while (stack.length) {
      const id = stack.pop();
      if (seen.has(id)) continue;
      seen.add(id);
      const unit = units.get(id);
      if (unit) for (const next of unit.refs) stack.push(next);
    }
    return seen;
  }

  // Token roots: definitions whose name appears in a consumer source.
  const tokenEvidence = new Map(); // unitId -> evidence[]
  for (const [name, list] of nameToUnits) {
    const evidence = summarizeEvidence(scans, [name]);
    if (!evidence.length) continue;
    for (const unit of list) tokenEvidence.set(unit.id, evidence);
  }

  // A consumer imports a generated model by name, and a generator emits only the models its spec
  // reaches. An operation nobody calls must stay when it is the only path by which its spec still
  // generates a model that a consumer uses.
  const ownerSpecs = [...new Set(operations.map((op) => op.spec))];
  for (const spec of ownerSpecs) {
    const specOps = operations.filter((op) => op.spec === spec);
    const keptReach = reach(specOps.filter((op) => op.status !== 'unreferenced').flatMap((op) => [...op.unitRefs]));
    for (const op of specOps.filter((candidate) => candidate.status === 'unreferenced')) {
      const opReach = reach([...op.unitRefs]);
      const needed = [...opReach].filter((id) => tokenEvidence.has(id) && !keptReach.has(id));
      if (!needed.length) continue;
      op.status = 'needed-for-models';
      op.neededModels = needed.slice(0, 5);
      for (const id of reach([...op.unitRefs])) keptReach.add(id);
    }
  }

  const kept = (statuses) => operations.filter((op) => statuses.includes(op.status));
  const allKeptStatuses = ['used', 'used-by-tests-only', 'held-by-pinned-consumer', 'handler-only', 'needed-for-models', 'unknown'];
  const withoutHandlerOnly = ['used', 'used-by-tests-only', 'held-by-pinned-consumer', 'needed-for-models', 'unknown'];

  const tokenRootIds = (filter) => [...tokenEvidence.entries()].filter(([, ev]) => filter(ev)).map(([id]) => id);
  const anyToken = () => true;
  // Evidence that exists only inside API controller files is the handler side of a handler-only
  // operation, so it does not keep a definition alive in the second pass.
  const nonHandlerToken = (ev) => ev.some((e) => e.hasProd || e.hasTest);

  const reachKept = reach([
    ...kept(allKeptStatuses).flatMap((op) => [...op.unitRefs]),
    ...tokenRootIds(anyToken),
  ]);
  const reachWithoutHandlerOnly = reach([
    ...kept(withoutHandlerOnly).flatMap((op) => [...op.unitRefs]),
    ...tokenRootIds(nonHandlerToken),
  ]);
  const reachPinnedFree = reach([
    ...kept(['used', 'used-by-tests-only', 'handler-only', 'needed-for-models', 'unknown']).flatMap((op) => [...op.unitRefs]),
    ...tokenRootIds((ev) => ev.some((e) => !e.pinned)),
  ]);

  const definitions = [];
  for (const unit of units.values()) {
    if (unit.kind === 'pathItem' || unit.kind === 'securitySchemes') continue;
    let status;
    if (!reachKept.has(unit.id)) status = 'unused';
    else if (!reachPinnedFree.has(unit.id)) status = 'held-by-pinned-consumer';
    else if (!reachWithoutHandlerOnly.has(unit.id)) status = 'only-via-handler-only-operations';
    else status = 'used';
    definitions.push({
      id: unit.id,
      kind: unit.kind,
      name: unit.name,
      file: rel(unit.file),
      status,
      evidence: (tokenEvidence.get(unit.id) || []).map((e) => ({ consumer: e.consumer, prod: e.prod, test: e.test, handler: e.handler })),
    });
  }
  return { definitions };
}

