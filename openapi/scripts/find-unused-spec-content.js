// Consumer scanning

function listCandidateFiles(root) {
  // Tracked and untracked-but-not-ignored files: gitignored output (generated clients, build
  // artifacts, scratch copies) is never hand-written source.
  const result = spawnSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard'], {
    cwd: root,
    maxBuffer: 256 * 1024 * 1024,
  });
  if (result.status !== 0) throw new Error(`git ls-files failed in ${root}: ${result.stderr}`);
  return result.stdout.toString('utf8').split('\0').filter(Boolean);
}

function walkSources(root, consumerName, onFile) {
  const skipPaths = (SKIP_PATHS[consumerName] || []).map((p) => `${p}/`);
  for (const relFile of listCandidateFiles(root)) {
    const segments = relFile.split('/');
    if (segments.slice(0, -1).some((segment) => SKIP_DIRS.has(segment) || segment.startsWith('.') || segment.endsWith('.egg-info'))) continue;
    if (skipPaths.some((prefix) => relFile.startsWith(prefix))) continue;
    if (!SOURCE_EXTENSIONS.has(path.extname(relFile)) || SKIP_FILENAMES.test(relFile)) continue;
    const abs = path.join(root, relFile);
    if (fs.existsSync(abs)) onFile(abs);
  }
}

const TOKEN_RE = /[A-Za-z_][A-Za-z0-9_]*/g;
const PATH_LITERAL_RE = /(['"`])([^'"`\s\n]*\/[^'"`\s\n]*)\1/g;

function normalizePath(raw) {
  return raw
    .replace(/\\/g, '')
    .replace(/\$\{[^}]*\}/g, '{}')
    .replace(/\{[^}/]*\}/g, '{}')
    .replace(/(^|\/)[:*][A-Za-z_][A-Za-z0-9_]*/g, '$1{}')
    .split('?')[0]
    .replace(/^https?:\/\/[^/]+/, '')
    .replace(/^(\{\}\/)+/, '') // a leading template variable is a base URL, not a path segment
    .replace(/^\/+/, '')
    .replace(/^api\/v1\//, '')
    .replace(/\/+$/, '');
}

function scanConsumer(consumer, root) {
  const tokens = new Map(); // token -> { prod:Set, test:Set, handler:Set }  (file lists capped)
  const paths = new Map(); // normalized path -> { prod:[], test:[] }
  const controllerFiles = [];
  const constSources = []; // for route resolution (server only)
  let fileCount = 0;

  const note = (map, key, bucket, file) => {
    let entry = map.get(key);
    if (!entry) {
      entry = { prod: [], test: [], handler: [] };
      map.set(key, entry);
    }
    const list = entry[bucket];
    if (list.length < 3 && !list.includes(file)) list.push(file);
    return entry;
  };

  walkSources(root, consumer.name, (abs) => {
    let size;
    try {
      size = fs.statSync(abs).size;
    } catch {
      return;
    }
    if (size > MAX_FILE_BYTES) return;
    const text = fs.readFileSync(abs, 'utf8');
    if (GENERATED_HEADER.test(text.slice(0, 2000))) return;
    fileCount += 1;
    const relFile = path.relative(root, abs);
    const isTest = TEST_PATH.test(relFile);
    const isHandler = !isTest && /@Controller\s*\(/.test(text);
    if (isHandler) controllerFiles.push({ abs, relFile, text });
    if (consumer.name === 'api' && /\.ts$/.test(abs)) constSources.push(text);
    const bucket = isTest ? 'test' : isHandler ? 'handler' : 'prod';

    const seen = new Set(text.match(TOKEN_RE) || []);
    for (const token of seen) note(tokens, token, bucket, relFile);

    for (const match of text.matchAll(PATH_LITERAL_RE)) {
      const normalized = normalizePath(match[2]);
      if (normalized.length < 3) continue;
      note(paths, normalized, bucket, relFile);
    }
  });

  const generatedConstants = path.join(root, 'src/generated/api/path-constants.ts');
  if (consumer.name === 'api' && fs.existsSync(generatedConstants)) constSources.push(fs.readFileSync(generatedConstants, 'utf8'));

  return { consumer, root, tokens, paths, controllerFiles, constSources, fileCount };
}

